export function MorphBlobs() {
  const containerRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const container = containerRef.current;
    if (!container) return;

    const blobs = container.querySelectorAll<SVGSVGElement>(".morph-blob");
    const tweens: gsap.core.Tween[] = [];

    blobs.forEach((blob, i) => {
      const config = BLOBS[i];
      if (!config) return;

      const paths = blob.querySelectorAll("path");
      if (paths.length < 2) return;

      gsap.set(paths[0], { attr: { d: config.paths[0] } });

      const tl = gsap.timeline({
        scrollTrigger: {
          trigger: container,
          start: config.scrollStart,
          end: config.scrollEnd,
          scrub: 1.5,
        },
      });

      for (let j = 1; j < config.paths.length; j++) {
        tl.to(paths[0], {
          attr: { d: config.paths[j] },
          duration: 1,
          ease: "power2.inOut",
        });
      }

      const spinTween = gsap.to(blob, {
        rotation: 360,
        ease: "none",
        scrollTrigger: {
          trigger: container,
          start: "top bottom",
          end: "bottom top",
          scrub: 3,
        },
      });

      const scaleTween = gsap.to(blob, {
        scale: 1.15,
        ease: "power1.inOut",
        scrollTrigger: {
          trigger: container,
          start: "top bottom",
          end: "bottom top",
          scrub: 2,
        },
      });

      tweens.push(spinTween, scaleTween);
    });

    return () => {
      tweens.forEach((t) => {
        t.scrollTrigger?.kill();
        t.kill();
      });
    };
  }, []);

  return (
    <div
      ref={containerRef}
      className="absolute inset-0 overflow-hidden pointer-events-none z-0"
      aria-hidden="true"
    >
      {BLOBS.map((blob, i) => (
        <svg
          key={i}
          className="morph-blob absolute will-change-transform"
          viewBox="-100 -100 200 200"
          style={{
            left: blob.x,
            top: blob.y,
            width: blob.size,
            height: blob.size,
            transform: "translate(-50%, -50%)",
          }}
        >
          <path
            d={blob.paths[0]}
            fill={blob.color}
            style={{ filter: "blur(20px)" }}
          />
        </svg>
      ))}
    </div>
  );
}
